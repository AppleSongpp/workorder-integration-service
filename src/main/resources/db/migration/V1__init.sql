-- Standard SQL only, so the same migration runs on H2 and PostgreSQL.

CREATE SEQUENCE work_order_seq START WITH 1001 INCREMENT BY 1;

CREATE TABLE work_order (
    id            BIGINT                   NOT NULL PRIMARY KEY,
    source_system VARCHAR(32)              NOT NULL,
    description   VARCHAR(1000)            NOT NULL,
    status        VARCHAR(32)              NOT NULL,
    version       BIGINT                   NOT NULL,
    created_by    VARCHAR(512)             NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_work_order_source_system CHECK (source_system IN ('SDP', 'QTSOS')),
    CONSTRAINT ck_work_order_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'COMPLETED'))
);

-- One row per successfully processed (caller, Idempotency-Key) pair.
-- The unique constraint is what prevents duplicate work orders under concurrency.
CREATE TABLE idempotency_record (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       VARCHAR(512)             NOT NULL,
    idempotency_key VARCHAR(128)             NOT NULL,
    request_hash    VARCHAR(64)              NOT NULL,
    work_order_id   BIGINT                   NOT NULL REFERENCES work_order (id),
    response_status INT                      NOT NULL,
    response_body   VARCHAR(8000)            NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_client_key UNIQUE (client_id, idempotency_key)
);

CREATE INDEX ix_idempotency_expires_at ON idempotency_record (expires_at);

-- Transactional outbox: events are written in the same transaction as the state change.
CREATE TABLE outbox_event (
    id           UUID                     NOT NULL PRIMARY KEY,
    event_type   VARCHAR(64)              NOT NULL,
    aggregate_id VARCHAR(64)              NOT NULL,
    payload      VARCHAR(8000)            NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_unpublished ON outbox_event (published_at, created_at);
